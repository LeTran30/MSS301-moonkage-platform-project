package com.moonkage.orchestrator.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import java.time.Instant;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;

/**
 * Idempotency and delivery log entity for received notification events.
 * Guarantees that duplicate deliveries of the same eventId are safely ignored.
 */
@Entity
@Table(
        name = "notification_event_logs",
        indexes = {
            @Index(name = "idx_notification_event_recipient", columnList = "recipient"),
            @Index(name = "idx_notification_event_status", columnList = "status")
        })
@Getter
@Setter
@NoArgsConstructor
public class NotificationEventLog {

    /** Unique eventId generated by publisher for idempotency. */
    @Id
    @Column(name = "event_id", nullable = false, length = 64)
    private String eventId;

    @Column(nullable = false)
    private String recipient;

    @Column(nullable = false)
    private String subject;

    @Column(name = "template_code", nullable = false)
    private String templateCode;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private DeliveryStatus status;

    @Column(name = "error_message", columnDefinition = "TEXT")
    private String errorMessage;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "sent_at")
    private Instant sentAt;
}
