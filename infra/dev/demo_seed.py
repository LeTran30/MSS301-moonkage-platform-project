def payment_sql(orders: list[Order]) -> str:
    out = ["-- the money side of the demo orders of the order seed: paid by VNPay, held, refunded, paid out"]
    payments, allocations, ledgers, entries, payouts, refunds, snapshots = [], [], [], [], [], [], []
    for o in orders:
        pay = o.child("payment")
        payments.append((pay, o.total, "VNPAY", "SUCCEEDED", "CHECKOUT", o.child("checkout"), o.buyer,
                         hashlib.md5(f"{o.id}:txn".encode()).hexdigest(), str(14000000 + o.seq * 37), "00",
                         o.child("checkout"), Raw(ago(o.expires_at)), Raw(ago(o.paid_at)), Raw(ago(o.opened_at)),
                         Raw(ago(o.paid_at))))
        allocations.append((pay, o.id, o.total))
        entries.append((o.child("entry:collect"), o.id, "COLLECT", o.total, pay, None, Raw(ago(o.paid_at))))
        refunded = o.dispute.refund if o.dispute and o.dispute.refund else 0
        if refunded:
            refund = o.child("refund")
            refunds.append((refund, o.id, "DISPUTE", o.child("dispute"), pay, refunded, "SUCCEEDED",
                            f"RF{o.seq:06d}", Raw(ago(o.dispute_resolved_at)), Raw(ago(o.dispute_resolved_at))))
            entries.append((o.child("entry:refund"), o.id, "REFUND", refunded, refund, ADMIN,
                            Raw(ago(o.dispute_resolved_at))))
        paid_out = o.total - refunded if o.paid_out else 0
        if o.paid_out:
            payout = o.child("payout")
            payouts.append((payout, o.id, o.vendor.id, paid_out, ADMIN, Raw(ago(o.payout_at))))
            entries.append((o.child("entry:payout"), o.id, "PAYOUT", paid_out, payout, ADMIN, Raw(ago(o.payout_at))))
        ledgers.append((o.child("ledger"), o.id, o.vendor.id, o.total, o.total - refunded - paid_out, 0, refunded,
                        paid_out, Raw(ago_date(o.deadline)) if o.reached("DELIVERED") else None,
                        1 + (1 if refunded else 0) + (1 if o.paid_out else 0), Raw(ago(o.updated))))
        open_dispute = bool(o.dispute and not o.dispute.decision)
        snapshots.append((o.id, o.vendor.id, "BUY_NOW", o.interprovince, o.total, o.status,
                          Raw(ago(o.deadline)) if o.reached("DELIVERED") else None, o.reached("COMPLETED"),
                          open_dispute, o.version, Raw(ago(o.updated))))
    out.append(insert(
        "payments", "id, amount, method, status, purpose, reference_id, payer_account_id, gateway_txn_ref, "
                    "gateway_txn_no, gateway_response_code, idempotency_key, expires_at, paid_at, created_at, "
                    "updated_at", payments))
    out.append(insert("payment_allocations", "payment_id, order_id, amount", allocations))
    out.append(insert(
        "ledgers", "id, order_id, vendor_id, total_collected, held, disbursed, refunded, paid_out, "
                   "expected_payout_date, version, updated_at", ledgers))
    out.append(insert("refunds", "id, order_id, reason, dispute_id, original_payment_id, amount, status, "
                                 "gateway_refund_ref, created_at, updated_at", refunds))
    out.append(insert("payouts", "id, order_id, vendor_id, amount, approved_by, created_at", payouts))
    out.append(insert("ledger_entries", "id, order_id, kind, amount, reference_id, actor_account_id, created_at",
                      entries))
    out.append(insert(
        "order_snapshots", "order_id, vendor_id, kind, interprovince, total_amount, status, complaint_deadline, "
                           "received_confirmed, dispute_open, source_version, updated_at", snapshots))
    return "\n".join(out)


