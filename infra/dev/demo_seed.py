# the newest orders, hours ago: two in each open step, so every order screen has something to act on
RECENT_HOURS = [2, 4, 8, 12, 20, 30, 53, 67]


def pick_age_minutes(i: int) -> int:
    """Spread the older orders over the rest of the four weeks, a little denser near today like a real season."""
    day = 3 + int((HISTORY_DAYS - 3) * RNG.random() ** 1.3)
    day = min(HISTORY_DAYS - 1, day)
    minute_of_day = RNG.randint(7 * 60, 22 * 60)
    return day * MINUTES_PER_DAY + (MINUTES_PER_DAY - minute_of_day) + i  # +i keeps them distinct


def status_for(order: Order) -> str:
    age_days = order.created / MINUTES_PER_DAY
    if age_days < 0.25:
        return "PAID"
    if age_days < 0.6:
        return "CONFIRMED"
    if order.delivered_at <= 0:
        return "SHIPPING"
    # the complaint window closed: the order completes on its own; before that the buyer may confirm early
    if order.deadline > 0:
        return "COMPLETED"
    if order.received_at > 0 and RNG.random() < 0.5:
        return "COMPLETED"
    return "DELIVERED"


def build_orders() -> list[Order]:
    buyers = list(BUYER_WEIGHTS)
    weights = [BUYER_WEIGHTS[b] for b in buyers]
    older = [pick_age_minutes(i) for i in range(ORDER_COUNT - len(RECENT_HOURS))]
    ages = sorted(older + [h * 60 for h in RECENT_HOURS], reverse=True)
    orders: list[Order] = []
    for seq, created in enumerate(ages, start=1):
        buyer = RNG.choices(buyers, weights)[0]
        address = RNG.choice([a for a in ADDRESSES if a.account_id == buyer])
        local = [v for v in SHOP_VENDORS if address.province_code in v.areas]
        vendor = RNG.choice(local) if local and RNG.random() < 0.75 else RNG.choice(SHOP_VENDORS)
        reachable = [p for p in SHOP_PRODUCTS if p.vendor is vendor
                     and (p.label == "NATIONWIDE" or address.province_code in vendor.areas)]
        count = RNG.choices([1, 2, 3], [5, 3, 1])[0]
        lines = [Line(p, RNG.choices([1, 2, 3, 5], [6, 4, 2, 1])[0])
                 for p in RNG.sample(reachable, min(count, len(reachable)))]
        order = Order(seq, buyer, address, vendor, lines, created)
        order.status = status_for(order)
        orders.append(order)

    completed = [o for o in orders if o.status == "COMPLETED"]
    # money for completed orders whose complaint window closed more than a day ago went to the vendor already, but
    # the two most recent of them still wait: the admin demo approves a payout (demo step 8)
    payable = [o for o in completed if o.payout_at > 0]
    for o in payable[:-2]:
        o.paid_out = True

    # one resolved partial refund, one rejected complaint, one still open on a delivered order
    oldest = [o for o in completed if o.paid_out]
    partial, rejected = oldest[2], oldest[6]
    partial.dispute = Dispute("DAMAGED", "Hai bánh trong hộp bị vỡ, nhân tràn ra hộp. Có ảnh chụp lúc mở hộp.",
                              "PARTIAL_REFUND", "Ảnh cho thấy 2 bánh vỡ do đóng gói. Hoàn tiền phần bánh hỏng.",
                              refund=partial.lines[0].product.price // 2)
    rejected.dispute = Dispute("LATE_DELIVERY", "Đơn giao muộn hơn dự kiến một ngày.",
                               "REJECTED", "Đơn giao trong thời hạn Shop cam kết; không có thiệt hại về hàng.")
    delivered = [o for o in orders if o.status == "DELIVERED" and o.dispute_opened_at > 0]
    if delivered:
        delivered[0].dispute = Dispute("WRONG_ITEM", "Đặt bánh nhân hạt sen nhưng trong hộp có 2 bánh nhân đậu đỏ.")

    for o in completed:
        if RNG.random() < 0.7:
            for line in o.lines:
                rating = RNG.choices([5, 4, 3, 2], [10, 6, 2, 1])[0]
                o.reviews.append((line.product, rating, RNG.choice(REVIEW_TEXTS[rating])))
    return orders


