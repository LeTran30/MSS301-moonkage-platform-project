def fixed_id(kind: int, seq: int) -> str:
    """An ID of the registry in docs/guides/database.md section 5."""
    return f"00000000-0000-4000-8000-{kind:04d}{seq:08d}"


def derived_id(*parts: object) -> str:
    """Same as md5(a || ':' || b)::uuid in Postgres: a child row's ID follows from its parent."""
    return str(uuid.UUID(hex=hashlib.md5(":".join(str(p) for p in parts).encode()).hexdigest()))


