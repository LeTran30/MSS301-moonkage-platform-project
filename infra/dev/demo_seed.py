def ago(minutes: int) -> str:
    return f"now() - interval '{minutes} minutes'"


def ago_date(minutes: int) -> str:
    return f"(now() - interval '{minutes} minutes')::date"


def lit(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, Raw):
        return value.sql
    return "'" + str(value).replace("'", "''") + "'"


@dataclass(frozen=True)
class Raw:
    sql: str


def values(rows: list[tuple]) -> str:
    return ",\n       ".join("(" + ", ".join(lit(v) for v in row) + ")" for row in rows)


def insert(table: str, columns: str, rows: list[tuple], conflict: str = "ON CONFLICT DO NOTHING") -> str:
    if not rows:
        return ""
    return f"INSERT INTO {table} ({columns})\nVALUES {values(rows)}\n{conflict};\n"


def text_array(items: list[str]) -> Raw:
    return Raw("'{" + ",".join(items) + "}'")


def jsonb(value: object) -> Raw:
    return Raw(lit(json.dumps(value, ensure_ascii=False)) + "::jsonb")


