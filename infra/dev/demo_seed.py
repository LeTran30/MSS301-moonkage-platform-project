def seed_path(service: str) -> Path:
    return API / service / "src/main/resources/db/seed/R__seed.sql"


def write_block(service: str, body: str) -> None:
    path = seed_path(service)
    text = path.read_text(encoding="utf-8")
    block = f"{BEGIN}\n{body.rstrip()}\n{END}\n"
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head + block + tail
    else:
        text = text.rstrip("\n") + "\n\n" + block
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_nfc() -> None:
    path = API / "identity-service/src/main/resources/db/seed/nfc-profiles.json"
    profiles = json.loads(path.read_text(encoding="utf-8"))
    known = {p["accountId"] for p in profiles}
    profiles += [p for p in nfc_profiles() if p["accountId"] not in known]
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(profiles, ensure_ascii=False, indent=2) + "\n")


def copy_images() -> None:
    for vendor_id, file in sorted({(p.vendor.id, p.image_file) for p in SHOP_PRODUCTS}):
        target = MINIO_SEED / vendor_id / file
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(IMAGE_SOURCE / file, target)


def main() -> None:
    orders = build_orders()
    copy_images()
    write_block("identity-service", identity_sql())
    write_nfc()
    write_block("vendor-service", vendor_sql(orders))
    write_block("catalog-service", catalog_sql(orders))
    write_block("quotation-service", quotation_sql())
    write_block("order-service", order_sql(orders))
    write_block("payment-service", payment_sql(orders))
    by_status: dict[str, int] = {}
    for o in orders:
        by_status[o.status] = by_status.get(o.status, 0) + 1
    print(f"orders: {len(orders)} {by_status}; paid out: {sum(o.paid_out for o in orders)}; "
          f"awaiting payout: {sum(o.status == 'COMPLETED' and not o.paid_out for o in orders)}; "
          f"disputes: {sum(1 for o in orders if o.dispute)}; reviews: {sum(len(o.reviews) for o in orders)}; "
          f"revenue: {sum(o.total for o in orders):,} VND")


if __name__ == "__main__":
    main()
