@dataclass
class Line:
    product: Product
    qty: int

    @property
    def subtotal(self) -> int:
        return self.product.price * self.qty


@dataclass
class Dispute:
    reason: str
    description: str
    decision: str | None = None
    decision_reason: str | None = None
    refund: int = 0


@dataclass
class Order:
    seq: int
    buyer: str
    address: Address
    vendor: Vendor
    lines: list[Line]
    created: int  # minutes ago
    status: str = "PAID"
    paid_out: bool = False
    dispute: Dispute | None = None
    reviews: list[tuple[Product, int, str]] = field(default_factory=list)

    @property
    def id(self) -> str:
        return fixed_id(5, self.seq)

    def child(self, kind: str) -> str:
        return derived_id(self.id, kind)

    @property
    def interprovince(self) -> bool:
        return self.address.province_code not in self.vendor.areas

    @property
    def items(self) -> int:
        return sum(line.subtotal for line in self.lines)

    @property
    def shipping(self) -> int:
        return INTERPROVINCE_FEE if self.interprovince else self.vendor.local_fee

    @property
    def total(self) -> int:
        return self.items + self.shipping

    # the steps of a buy-now order, minutes ago; None when the order has not got there yet
    STEPS = ["PAID", "CONFIRMED", "SHIPPING", "DELIVERED", "COMPLETED"]

    def reached(self, step: str) -> bool:
        return self.STEPS.index(self.status) >= self.STEPS.index(step)

    @property
    def opened_at(self) -> int:
        """Checkout and payment were made a few minutes before the order (the order is created on payment)."""
        return self.created + 3

    @property
    def expires_at(self) -> int:
        return self.opened_at - 15

    @property
    def paid_at(self) -> int:
        return self.created + 1

    @property
    def confirmed_at(self) -> int:
        return self.created - 90

    @property
    def shipped_at(self) -> int:
        return self.created - 20 * 60

    @property
    def delivered_at(self) -> int:
        return self.created - (60 if self.interprovince else 36) * 60

    @property
    def dispute_opened_at(self) -> int:
        return self.delivered_at - 4 * 60

    @property
    def dispute_resolved_at(self) -> int:
        return self.dispute_opened_at - 24 * 60

    @property
    def received_at(self) -> int:
        # a buyer with a complaint confirms receipt once the admin has decided it
        if self.dispute and self.dispute.decision:
            return self.dispute_resolved_at - 60
        return self.delivered_at - 6 * 60

    @property
    def deadline(self) -> int:
        return self.delivered_at - COMPLAINT_DAYS * MINUTES_PER_DAY

    @property
    def payout_at(self) -> int:
        return self.deadline - 12 * 60

    @property
    def updated(self) -> int:
        if self.paid_out:
            return self.payout_at
        return {"PAID": self.paid_at, "CONFIRMED": self.confirmed_at, "SHIPPING": self.shipped_at,
                "DELIVERED": self.delivered_at, "COMPLETED": self.received_at}[self.status]

    @property
    def version(self) -> int:
        return self.STEPS.index(self.status) + (1 if self.paid_out else 0)

    @property
    def tracking(self) -> str | None:
        return f"MK{7000000000 + self.seq * 7919}" if self.interprovince and self.reached("SHIPPING") else None


